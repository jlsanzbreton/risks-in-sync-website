export function generateReviews(repoRoot = DEFAULT_REPO_ROOT): { count: number; slugs: string[] } {
  const { published } = loadReviews(repoRoot);
  if (!published.length) throw new Error("No ready_for_pr reviews were found; refusing to generate an empty publication");

  const generatedSource = join(repoRoot, "src", "generated");
  mkdirSync(generatedSource, { recursive: true });
  const reviews = published.map(({ review }) => withImageDimensions(review, repoRoot));
  writeFileSync(
    join(generatedSource, "reviews.ts"),
    `// GENERATED by npm run generate:reviews. Do not edit.\nimport type { ReviewIssue } from "../content/review-types";\n\nexport const reviews: ReviewIssue[] = ${JSON.stringify(reviews, null, 2)};\n`,
  );

  const entries: Record<string, string> = {};
  for (const review of reviews) {
    const issueDirectory = join(repoRoot, "review", review.slug);
    mkdirSync(issueDirectory, { recursive: true });
    const entry = join(issueDirectory, "index.html");
    writeFileSync(entry, issueHtml(review));
    entries[`review-${review.slug}`] = relative(repoRoot, entry);
  }
  writeFileSync(
    join(repoRoot, "review", ".generated-entries.json"),
    `${JSON.stringify(entries, null, 2)}\n`,
  );
  return { count: reviews.length, slugs: reviews.map((review) => review.slug) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  try {
    const result = generateReviews();
    console.log(`Generated ${result.count} review${result.count === 1 ? "" : "s"}: ${result.slugs.join(", ")}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
