import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { DEFAULT_REPO_ROOT, loadReviews } from "./reviews";
import type { ReviewImage, ReviewIssue } from "../src/content/review-types";

const SITE_URL = "https://risksinsync.com";
const FALLBACK_IMAGE = "/risksinsync-og.png";
const FALLBACK_ALT = "Risks In Sync";

function uint24LE(buffer: Buffer, offset: number): number {
  return buffer[offset] | (buffer[offset + 1] << 8) | (buffer[offset + 2] << 16);
}

function imageDimensions(file: string): { width: number; height: number } | null {
  const data = readFileSync(file);
  if (data.length >= 24 && data.toString("ascii", 1, 4) === "PNG") {
    return { width: data.readUInt32BE(16), height: data.readUInt32BE(20) };
  }
  if (data.length >= 30 && data.toString("ascii", 0, 4) === "RIFF" && data.toString("ascii", 8, 12) === "WEBP") {
    const chunk = data.toString("ascii", 12, 16);
    if (chunk === "VP8X") return { width: uint24LE(data, 24) + 1, height: uint24LE(data, 27) + 1 };
    if (chunk === "VP8 ") return { width: data.readUInt16LE(26) & 0x3fff, height: data.readUInt16LE(28) & 0x3fff };
    if (chunk === "VP8L") {
      return {
        width: 1 + data[21] + ((data[22] & 0x3f) << 8),
        height: 1 + ((data[22] & 0xc0) >> 6) + (data[23] << 2) + ((data[24] & 0x0f) << 10),
      };
    }
  }
  if (data.length >= 4 && data[0] === 0xff && data[1] === 0xd8) {
    let offset = 2;
    while (offset + 9 < data.length) {
      if (data[offset] !== 0xff) { offset += 1; continue; }
      const marker = data[offset + 1];
      if (marker >= 0xc0 && marker <= 0xc3) return { width: data.readUInt16BE(offset + 7), height: data.readUInt16BE(offset + 5) };
      offset += 2 + data.readUInt16BE(offset + 2);
    }
  }
  return null;
}

function withImageDimensions(review: ReviewIssue, repoRoot: string): ReviewIssue {
  return {
    ...review,
    images: review.images.map((image) => {
      const dimensions = imageDimensions(join(repoRoot, "public", "review", review.slug, ...image.path.split("/")));
      return dimensions ? { ...image, intrinsic_width: dimensions.width, intrinsic_height: dimensions.height } : image;
    }),
  };
}

function html(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function publicImagePath(review: ReviewIssue, image: ReviewImage): string {
  return `/review/${review.slug}/${image.path}`;
}

